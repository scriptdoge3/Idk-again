"""Writers for Half-Life file formats: Valve 220 .map, WAD3 textures, WAV with loop cue."""
import struct
import numpy as np
from PIL import Image


# ------------------------------------------------------------------- .map
def _fmt(v):
    s = f'{v:.4f}'.rstrip('0').rstrip('.')
    return '0' if s in ('-0', '') else s


AXES = {  # outward normal -> (U, V) world-aligned texture axes, as editors write them
    (0, 0, 1): ((1, 0, 0), (0, -1, 0)), (0, 0, -1): ((1, 0, 0), (0, -1, 0)),
    (1, 0, 0): ((0, 1, 0), (0, 0, -1)), (-1, 0, 0): ((0, 1, 0), (0, 0, -1)),
    (0, 1, 0): ((1, 0, 0), (0, 0, -1)), (0, -1, 0): ((1, 0, 0), (0, 0, -1)),
}


class Box:
    """Axis-aligned brush. faces: dict normal -> (texture, (uoff, voff, sx, sy)) ; default for the rest."""

    def __init__(self, x0, y0, z0, x1, y1, z1, tex='sc_black', faces=None, scale=1.0):
        self.lo = (min(x0, x1), min(y0, y1), min(z0, z1))
        self.hi = (max(x0, x1), max(y0, y1), max(z0, z1))
        self.tex = tex
        self.scale = scale
        self.faces = faces or {}

    def lines(self):
        (x0, y0, z0), (x1, y1, z1) = self.lo, self.hi
        out = []
        for n in AXES:
            axis = [i for i in range(3) if n[i]][0]
            d = (self.hi if n[axis] > 0 else self.lo)[axis]
            # three corners on the face, ordered so (p0-p1)x(p2-p1) points along n
            others = [i for i in range(3) if i != axis]
            a, b = others
            pts = []
            for (ua, ub) in ((0, 0), (1, 0), (1, 1)):
                p = [0, 0, 0]
                p[axis] = d
                p[a] = (self.lo, self.hi)[ua][a]
                p[b] = (self.lo, self.hi)[ub][b]
                pts.append(p)
            p0, p1, p2 = [np.array(p, float) for p in pts]
            if np.dot(np.cross(p0 - p1, p2 - p1), n) < 0:
                p0, p2 = p2, p0
            U, V = AXES[n]
            tex, tx = self.faces.get(n, (self.tex, None))
            if tx is None:
                uoff, voff, sx, sy = 0, 0, self.scale, self.scale
            else:
                uoff, voff, sx, sy = tx
            pt = ' '.join('( ' + ' '.join(_fmt(c) for c in p) + ' )' for p in (p0, p1, p2))
            out.append(f'{pt} {tex} [ {U[0]} {U[1]} {U[2]} {_fmt(uoff)} ] [ {V[0]} {V[1]} {V[2]} {_fmt(voff)} ] 0 {_fmt(sx)} {_fmt(sy)}')
        return out


def face_map(x_left, z_top, ppu):
    """Texture transform so a front (-Y) face shows texel (0,0) at (x_left, z_top), ppu texels per unit."""
    s = 1.0 / ppu
    return (-x_left / s, z_top / s, s, s)


def face_map_up(x_left, y_far, ppu):
    """Same for an upward (+Z) face, texture top edge at y_far (towards +Y)."""
    s = 1.0 / ppu
    return (-x_left / s, y_far / s, s, s)


def write_map(path, world_brushes, entities):
    L = ['// Sable Creek Hydro - generated by goldsrc/build.py', '{']
    for k, v in entities[0].items():
        L.append(f'"{k}" "{v}"')
    for b in world_brushes:
        L.append('{'); L += b.lines(); L.append('}')
    L.append('}')
    for e in entities[1:]:
        L.append('{')
        for k, v in e.items():
            if k == '_brushes':
                continue
            L.append(f'"{k}" "{v}"')
        for b in e.get('_brushes', []):
            L.append('{'); L += b.lines(); L.append('}')
        L.append('}')
    open(path, 'w').write('\n'.join(L) + '\n')


# ------------------------------------------------------------------- WAD3
def _quantize(img):
    img = img.convert('RGB')
    q = img.quantize(colors=256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[:768]
    pal += [0] * (768 - len(pal))
    return q, pal


def write_wad(path, textures):
    """textures: dict name -> PIL image (sizes multiples of 16)."""
    lumps = []
    for name, img in textures.items():
        w, h = img.size
        assert w % 16 == 0 and h % 16 == 0, f'{name} {img.size}'
        assert len(name) <= 15, name
        q, pal = _quantize(img)
        mips = [np.asarray(q, dtype=np.uint8)]
        rgb = img.convert('RGB')
        for m in (1, 2, 3):
            small = rgb.resize((w >> m, h >> m), Image.Resampling.BOX)
            mips.append(np.asarray(small.quantize(palette=q, dither=Image.Dither.NONE), dtype=np.uint8))
        header = struct.pack('<16sII', name.encode('ascii'), w, h)
        off = 16 + 8 + 16
        offs = []
        for m in mips:
            offs.append(off); off += m.size
        data = header + struct.pack('<4I', *offs) + b''.join(m.tobytes() for m in mips)
        data += struct.pack('<H', 256) + bytes(pal) + b'\x00\x00'
        lumps.append((name, data))
    out = bytearray(b'WAD3' + struct.pack('<II', len(lumps), 0))
    dirs = []
    for name, data in lumps:
        dirs.append((len(out), len(data), name))
        out += data
        while len(out) % 4:
            out += b'\x00'
    dir_off = len(out)
    for pos, size, name in dirs:
        out += struct.pack('<IIIbbH16s', pos, size, size, 0x43, 0, 0, name.encode('ascii'))
    out[8:12] = struct.pack('<I', dir_off)
    open(path, 'wb').write(bytes(out))


# -------------------------------------------------------------------- WAV
def write_wav(path, samples, rate=22050, loop=False):
    """16-bit mono PCM; a 'cue ' chunk marks it as looping for the GoldSrc sound engine."""
    s = np.clip(samples, -1, 1)
    pcm = (s * 32000).astype('<i2').tobytes()
    chunks = b'fmt ' + struct.pack('<IHHIIHH', 16, 1, 1, rate, rate * 2, 2, 16)
    chunks += b'data' + struct.pack('<I', len(pcm)) + pcm
    if len(pcm) % 2:
        chunks += b'\x00'
    if loop:
        cue = struct.pack('<I', 1) + struct.pack('<II4sIII', 1, 0, b'data', 0, 0, 0)
        chunks += b'cue ' + struct.pack('<I', len(cue)) + cue
    data = b'WAVE' + chunks
    open(path, 'wb').write(b'RIFF' + struct.pack('<I', len(data)) + data)
